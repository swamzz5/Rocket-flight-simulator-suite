% Rocket Design & Flight Simulation Suite
% Rocket Database
%
% NOTE ON STABILITY FIELDS (NoseLength, NoseType, Fin*, CG):
% These were added to support the Barrowman stability module
% (stability/barrowmanCP.m, stability/staticMargin.m). The original
% project data only ever specified mass/thrust/drag - it never
% captured actual shape. The geometry values below are ESTIMATES
% (plausible proportions for each rocket class), not measured data.
% Replace them with real measured values before trusting any static
% margin output for these entries.

% NOTE ON PROPULSIVE LANDING FIELDS (LandingFuelMass, LandingThrust):
% These support the suicide-burn recovery model (recovery/suicideBurnTrigger.m)
% instead of a parachute. LandingThrust defaults to MaxThrust, modeling
% "relight the main engine" rather than a separate landing thruster.
% LandingFuelMass values below are ESTIMATES, not measured/designed data.
%
% IMPORTANT PHYSICAL CAVEAT: Estes Alpha III and Model Rocket 1 are
% modeled here as small COMMERCIAL SOLID-MOTOR rockets. Real solid
% rocket motors CANNOT relight or throttle once ignited - a propulsive
% landing is not physically achievable with this class of motor. Their
% LandingFuelMass/LandingThrust fields are included for numerical
% testability of the propulsive-landing code path only, not as a
% realistic design. The Sounding Rocket entry is the more physically
% defensible candidate for this feature (large sounding rockets can be
% liquid/hybrid-propelled, which do support restart/throttling).

