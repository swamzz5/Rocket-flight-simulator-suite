function outputPath = generateMissionReport(mission, outputPath)

%==========================================================
% Automated Mission Report Generator
% Rocket Design & Flight Simulation Suite
%
% Writes a Markdown mission report from a `mission` struct (as
% produced by simulation/runMission.m) covering vehicle, environment,
% flight, propulsion, stability, and recovery/reusability - the same
% sections outlined in the original project specification.
%
% Inputs:
%   mission    - struct from runMission.m
%   outputPath - (optional) file path to write to. Defaults to
%                'mission_report.md' in the current directory.
%
% Output:
%   outputPath - the path the report was actually written to
%==========================================================

if nargin < 2
    outputPath = 'mission_report.md';
end

r = mission.rocket;
res = mission.results;
ev = mission.events;

fid = fopen(outputPath, 'w');
if fid == -1
    error('generateMissionReport:cannotOpenFile', 'Could not open %s for writing.', outputPath);
end

fprintf(fid, '# Mission Report: %s\n\n', r.Name);
fprintf(fid, '_Generated by Rocket Design & Flight Simulation Suite._\n\n');
fprintf(fid, ['> This is a numerical simulation using empirical/engineering-approximation ' ...
    'models (ISA atmosphere, piecewise-constant Cd(Mach), Barrowman subsonic stability, ' ...
    'idealized suicide-burn guidance). It is NOT a CFD result and is NOT flight-certified. ' ...
    'See Limitations at the end of this report.\n\n']);

%% Vehicle
fprintf(fid, '## Vehicle\n\n');
fprintf(fid, '| Property | Value |\n|---|---|\n');
fprintf(fid, '| Name | %s |\n', r.Name);
fprintf(fid, '| Diameter | %.4f m |\n', r.Diameter);
fprintf(fid, '| Length | %.4f m |\n', r.Length);
fprintf(fid, '| Empty Mass | %.4f kg |\n', r.EmptyMass);
fprintf(fid, '| Ascent Fuel Mass | %.4f kg |\n', r.FuelMass);
fprintf(fid, '| Landing Fuel Mass (reserved) | %.4f kg |\n', r.LandingFuelMass);
fprintf(fid, '| Reference Area | %.6f m^2 |\n', r.ReferenceArea);
fprintf(fid, '| Drag Model | Piecewise Cd(Mach), base Cd=%.2f |\n\n', r.Cd);

%% Environment
fprintf(fid, '## Environment\n\n');
atm0 = isaAtmosphere(max(mission.launchAltitude,0));
fprintf(fid, '| Property | Value |\n|---|---|\n');
fprintf(fid, '| Launch Altitude (MSL) | %.1f m |\n', mission.launchAltitude);
fprintf(fid, '| Temperature | %.2f K |\n', atm0.Temperature);
fprintf(fid, '| Pressure | %.2f Pa |\n', atm0.Pressure);
fprintf(fid, '| Density | %.4f kg/m^3 |\n', atm0.Density);
fprintf(fid, '| Atmosphere Model | ISA (valid 0-20,000 m, see isaAtmosphere.m) |\n\n');

%% Flight
fprintf(fid, '## Flight\n\n');
fprintf(fid, '| Metric | Value |\n|---|---|\n');
fprintf(fid, '| Flight Time | %.2f s |\n', res.time(end));
fprintf(fid, '| Apogee | %.2f m at t=%.2f s |\n', ev.ApogeeAltitude, ev.ApogeeTime);
fprintf(fid, '| Max Velocity | %.2f m/s |\n', ev.MaxVelocity);
fprintf(fid, '| Max Mach | %.2f at t=%.2f s |\n', ev.MaxMach, ev.MaxMachTime);
fprintf(fid, '| Max Acceleration | %.2f m/s^2 |\n', ev.MaxAcceleration);
fprintf(fid, '| Burnout | t=%.2f s, alt=%.2f m, v=%.2f m/s |\n', ...
    ev.BurnoutTime, ev.BurnoutAltitude, ev.BurnoutVelocity);
fprintf(fid, '| Impact Velocity | %.2f m/s |\n\n', ev.ImpactVelocity);

%% Propulsion
fprintf(fid, '## Propulsion\n\n');
totalImpulse = trapz(res.time(res.time<=r.BurnTime), res.thrust(res.time<=r.BurnTime));
fprintf(fid, '| Metric | Value |\n|---|---|\n');
fprintf(fid, '| Burn Time | %.2f s |\n', r.BurnTime);
fprintf(fid, '| Max Thrust | %.2f N |\n', r.MaxThrust);
fprintf(fid, '| Total Impulse (ascent) | %.1f N*s |\n\n', totalImpulse);

%% Stability
fprintf(fid, '## Stability\n\n');
fprintf(fid, '| Metric | Value |\n|---|---|\n');
fprintf(fid, '| Center of Pressure | %.4f m (from nose tip) |\n', mission.Cp);
fprintf(fid, '| Center of Gravity | %.4f m (from nose tip) |\n', r.CG);
fprintf(fid, '| CnAlpha (total) | %.3f per radian |\n', mission.CnAlpha);
fprintf(fid, '| Static Margin | %.2f calibers |\n', mission.staticMargin);
fprintf(fid, '| Status | %s |\n\n', mission.stabilityStatus);
fprintf(fid, ['_Barrowman method: subsonic, small-angle-of-attack, thin-fin theory. ' ...
    'Does not capture transonic CP shift near Mach 1._\n\n']);

%% Recovery / Reusability
fprintf(fid, '## Recovery / Reusability\n\n');
fprintf(fid, '| Metric | Value |\n|---|---|\n');
if ev.LandingBurnIgnited
    fprintf(fid, '| Landing Burn Ignited | t=%.2f s, alt=%.2f m |\n', ...
        ev.LandingBurnIgnitionTime, ev.LandingBurnIgnitionAltitude);
else
    fprintf(fid, '| Landing Burn Ignited | never |\n');
end
fprintf(fid, '| Landing Fuel Used | %.4f kg |\n', ev.LandingFuelUsed);
fprintf(fid, '| Landing Fuel Remaining | %.4f kg |\n', ev.LandingFuelRemaining);
fprintf(fid, '| Outcome | %s |\n\n', ev.LandingOutcome);

%% Limitations
fprintf(fid, '## Limitations\n\n');
fprintf(fid, [ ...
    '- 1D vertical flight only - no horizontal drift, wind, or launch angle.\n' ...
    '- Drag coefficient is a piecewise-constant function of Mach, not a continuous ' ...
    'or vehicle-specific aerodynamic model.\n' ...
    '- Barrowman stability method is subsonic/small-angle only.\n' ...
    '- Suicide-burn landing guidance is idealized: instant thrust on/off, no sensor ' ...
    'or actuator lag, no safety margin.\n' ...
    '- Rocket geometry (nose/fin dimensions, CG) for database entries are engineering ' ...
    'estimates, not measured hardware data, unless explicitly replaced by the user.\n' ...
    '- ISA atmosphere model is validated 0-20,000 m; results above that are flagged ' ...
    'extrapolations by isaAtmosphere.m.\n']);

fclose(fid);

end
